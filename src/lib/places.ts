export const airportCity = (code: string | null | undefined) => (code ? (AIRPORTS[code.toUpperCase()] ?? null) : null);

const fold = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();

const ALIAS_TO_CITY = new Map<string, string>();
for (const [city, aliases] of Object.entries(CITIES)) for (const alias of aliases) ALIAS_TO_CITY.set(fold(alias), city);
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const CITY_RE = new RegExp(
  `(?<![\\p{L}])(${[...ALIAS_TO_CITY.keys()]
    .sort((a, b) => b.length - a.length)
    .map(escape)
    .join('|')})(?![\\p{L}])`,
  'gu',
);

/**
 * Ciudades conocidas que aparecen en el texto, en orden y sin repetir.
 * `ignore`: palabras a no tomar como ciudad (los nombres de las personas: "Santiago", "Mendoza"…).
 */
export function findCities(text: string, ignore: string[] = []): string[] {
  let folded = fold(text);
  for (const word of ignore) {
    if (word.length >= 3)
      folded = folded.replace(new RegExp(`(?<![\\p{L}])${escape(fold(word))}(?![\\p{L}])`, 'gu'), ' ');
  }
  const found: string[] = [];
  for (const m of folded.matchAll(CITY_RE)) {
    const city = ALIAS_TO_CITY.get(m[1])!;
    if (!found.includes(city)) found.push(city);
  }
  return found;
}
